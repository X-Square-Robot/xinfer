_HEADER = """\
// The TVM-FFI faces of the {title} AOT kernels: per-kernel typed functions that marshal
// TensorView arguments and int64 scalars onto the packed-launch C ABI and launch on the
// current NPU stream. Generated by tools/aot_glue_gen.py from the generator manifests
// (tools/generate.py's own ``launcher_abi`` record); the python envelopes that call these
// faces own the validation - the ctypes bindings they replace had no checks of their own
// either. The declarations follow the packed-launch contract: void* per tensor, int64 per
// scalar, the stream last (the aarch64 C ABI passes pointers type-agnostically; the
// generated host code spells the same parameters with its typed pointers).
#include "common/aot_glue.h"

#include <cstdint>

namespace xinfer::aot::{ns}_glue {{
using xinfer::aot::glue::TensorView;

"""


def _parse(abi: str):
    """``(pointers, scalars)`` names of one launcher ABI string (the stream dropped)."""
    pointers, scalars = [], []
    for parameter in (part.strip() for part in abi.split(",")):
        if "stream" in parameter:
            continue
        name = parameter.split()[-1]
        (pointers if "*" in parameter else scalars).append(name)
    if not pointers:
        raise ValueError(f"every launcher takes a tensor first: {abi}")
    return pointers, scalars


def _face(kernel: str, abi: str) -> str:
    pointers, scalars = _parse(abi)
    cpp_params = "".join(f", TensorView {name}" for name in pointers)
    cpp_params += "".join(f", int64_t {name}" for name in scalars)
    c_params = "".join(", void*" for _ in pointers) + "".join(", int64_t" for _ in scalars)
    rest = "".join(f", {name}" for name in pointers[1:] + scalars)
    return f"""\
extern "C" {{
int32_t xinfer_aot_{kernel}_call({c_params.lstrip(", ")}, void* stream);
const char* xinfer_aot_{kernel}_get_last_error();
}}

void {kernel}({cpp_params.lstrip(", ")}) {{
  xinfer::aot::glue::Launch("{kernel}", xinfer_aot_{kernel}_call,
                            xinfer_aot_{kernel}_get_last_error, {pointers[0]}{rest});
}}
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--table", type=Path, required=True,
                        help="family|kernel|launcher_abi lines (the generator manifests' record)")
    parser.add_argument("--src", type=Path, required=True, help="the src/ tree to write into")
    parser.add_argument("--check", action="store_true",
                        help="verify the committed faces match a regeneration instead of writing")
    args = parser.parse_args()

    abis: dict[str, str] = {}
    for line in args.table.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line:
            family, kernel, abi = line.split("|", 2)
            abis[kernel] = abi
    where = {kernel: directory
             for directory, kernels in _DIRECTORIES.items() for kernel in kernels}
    unknown = set(abis) - set(where)
    missing = set(where) - set(abis)
    if unknown or missing:
        raise SystemExit(f"table mismatch: unknown={sorted(unknown)} missing={sorted(missing)}")

    for directory, kernels in _DIRECTORIES.items():
        chunks = [_HEADER.format(title=directory, ns=directory)]
        for kernel in sorted(kernels):
            chunks.append(_face(kernel, abis[kernel]))
            chunks.append(f"TVM_FFI_DLL_EXPORT_TYPED_FUNC({kernel}, "
                          f"xinfer::aot::{directory}_glue::{kernel});\n\n")
        chunks.append(f"}}  // namespace xinfer::aot::{directory}_glue\n")
        text = "".join(chunks)
        target = args.src / directory / "aot_glue.cc"
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                raise SystemExit(f"{target} does not match the table's regeneration")
        else:
            target.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {target} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
